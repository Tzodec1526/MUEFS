import ast
import io
import tokenize
from pathlib import Path

import sqlalchemy as sa
from alembic.autogenerate import render_python_code
from alembic.operations import ops
from mako.template import Template

TEMPLATE = Path(__file__).resolve().parents[1] / "alembic" / "script.py.mako"
AUTOGENERATED_START = "    # ### commands auto generated by Alembic - please adjust! ###"
AUTOGENERATED_END = "    # ### end Alembic commands ###"
SQL_WITH_A_HASH_LINE = "\n    # keep this sql\n    SELECT 1\n    "


def render(upgrades: str | None, downgrades: str | None = None) -> str:
    return Template(filename=str(TEMPLATE)).render(
        up_revision="aaaaaaaaaaaa", down_revision=None, branch_labels=None, depends_on=None,
        imports="", upgrades=upgrades, downgrades=downgrades,
    )


def syntax_error(source: str) -> str | None:
    try:
        compile(source, "revision.py", "exec")
    except SyntaxError as error:
        return str(error)
    return None


def statements(source: str, function: str) -> list[ast.stmt]:
    tree = ast.parse(source)
    return next(
        node.body for node in tree.body
        if isinstance(node, ast.FunctionDef) and node.name == function
    )


def comments(source: str) -> list[str]:
    return [
        token.string for token in tokenize.generate_tokens(io.StringIO(source).readline)
        if token.type == tokenize.COMMENT
    ]


def test_an_empty_autogenerated_body_renders_as_pass_with_no_comment() -> None:
    body = render_python_code(ops.UpgradeOps(ops=[]))

    source = render(body, body)

    assert syntax_error(source) is None
    assert comments(source) == []
    assert ast.get_docstring(ast.parse(source)) is None
    assert [type(node) for node in statements(source, "upgrade")] == [ast.Pass]
    assert [type(node) for node in statements(source, "downgrade")] == [ast.Pass]


def test_a_missing_body_renders_as_pass() -> None:
    source = render(None)

    assert syntax_error(source) is None
    assert [type(node) for node in statements(source, "upgrade")] == [ast.Pass]


def test_every_statement_of_an_ordinary_body_stays_inside_the_function() -> None:
    body = render_python_code(ops.UpgradeOps(ops=[
        ops.AddColumnOp("filings", sa.Column("note", sa.String(), nullable=True)),
        ops.DropColumnOp("filings", "old_note"),
    ]))

    source = render(body)

    assert syntax_error(source) is None
    assert comments(source) == []
    assert len(statements(source, "upgrade")) == 2
    assert [type(node) for node in statements(source, "downgrade")] == [ast.Pass]


def test_a_hash_line_inside_a_multiline_string_is_kept() -> None:
    body = "\n".join([
        AUTOGENERATED_START,
        '    op.execute("""',
        "    # keep this sql",
        "    SELECT 1",
        '    """)',
        AUTOGENERATED_END,
    ])

    source = render(body)

    assert syntax_error(source) is None
    assert comments(source) == []
    execute = statements(source, "upgrade")[0]
    assert isinstance(execute, ast.Expr) and isinstance(execute.value, ast.Call)
    assert ast.literal_eval(execute.value.args[0]) == SQL_WITH_A_HASH_LINE
